		enum KickData { // test for 5 posible kick position
			NE = [ ( 0, 0), (-1, 0), (-1, 1), ( 0,-2), (-1,-2) ], 
			EN = [ ( 0, 0), (+1, 0), (+1,-1), ( 0,+2), (+1,+2) ],
			ES = [ ( 0, 0), (+1, 0), (+1,-1), ( 0,+2), (+1,+2) ],
			SE = [ ( 0, 0), (-1, 0), (-1,+1), ( 0,-2), (-1,-2) ],
			SW = [ ( 0, 0), (+1, 0), (+1,+1), ( 0,-2), (+1,-2) ],
			WS = [ ( 0, 0), (-1, 0), (-1,-1), ( 0,+2), (-1,+2) ],
			WN = [ ( 0, 0), (-1, 0), (-1,-1), ( 0,+2), (-1,+2) ],
			NW = [ ( 0, 0), (+1, 0), (+1,+1), ( 0,-2), (+1,-2) ]
		}

		enum KickDataI {
			NE = [ ( 0, 0), (-2, 0), (+1, 0), (-2,-1), (+1,+2) ],
			EN = [ ( 0, 0), (+2, 0), (-1, 0), (+2,+1), (-1,-2) ],
			ES = [ ( 0, 0), (-1, 0), (+2, 0), (-1,+2), (+2,-1) ],
			SE = [ ( 0, 0), (+1, 0), (-2, 0), (+1,-2), (-2,+1) ],
			SW = [ ( 0, 0), (+2, 0), (-1, 0), (+2,+1), (-1,-2) ],
			WS = [ ( 0, 0), (-2, 0), (+1, 0), (-2,-1), (+1,+2) ],
			WN = [ ( 0, 0), (+1, 0), (-2, 0), (+1,-2), (-2,+1) ],
			NW = [ ( 0, 0), (-1, 0), (+2, 0), (-1,+2), (+2,-1) ]
		}
		
		(int, int)[] GetKickData(Piece piece, State pre, State post) {
			var pieceKickData;

			switch (piece) {
				case I:
					pieceKickData = KickDataI;
					break;
				case O:
					pieceKickData = KickDataO;
					break;
				default:
					pieceKickData = KickData;
					break;
			}


			switch ((pre, post)) {
				case (NORTH, EAST):
					return pieceKickData.NE;
				case (EAST, NORTH):
					return pieceKickData.EN;
				case (EAST, SOUTH):
					return pieceKickData.ES;
				case (SOUTH, EAST):
					return pieceKickData.SE;
				case (SOUTH, WEST):
					return pieceKickData.SW;
				case (WEST, SOUTH):
					return pieceKickData.WS;
				case (NORTH, WEST):
					return pieceKickData.WN;
				case (WEST, NORTH):
					return pieceKickData.NW;
			}
		}
